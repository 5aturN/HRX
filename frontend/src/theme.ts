export function tgColors() {
  const tg = (window as any).Telegram?.WebApp;
  const p = tg?.themeParams || {};
  const dark = tg?.colorScheme !== "light";
  if (!dark)
    return {
      dark: false,
      bg: p.bg_color || "#f2f2f7",
      card: "#ffffff",
      card2: "#e9e9ee",
      text: "#111111",
      muted: "#8e8e93",
      btn: p.button_color || "#007aff",
      btnText: "#ffffff",
      lime: "#dff83a",
      border: "rgba(0,0,0,.08)",
      danger: "#ff3b30",
      ok: "#248a3d",
    };
  return {
    dark: true,
    bg: p.bg_color || "#1a1a2e",
    card: p.secondary_bg_color || "#23233f",
    card2: "#2e2e4d",
    text: p.text_color || "#ffffff",
    muted: p.hint_color || "#9a9ab0",
    btn: "#dff83a",
    btnText: "#111111",
    lime: "#dff83a",
    border: "rgba(255,255,255,.1)",
    danger: "#ff453a",
    ok: "#30d158",
  };
}

